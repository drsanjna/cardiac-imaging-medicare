"""RUNS_DIR/index.html: every run, newest first, with status, commit, headline IRRs and links to its gallery, PDF and log."""
from pathlib import Path

from .. import config
from .gallery import CSS, esc
from .run_store import list_runs


def build(runs_dir=None):
    """Rewrite index.html in runs_dir from the manifests of all runs."""
    runs_dir = Path(runs_dir or config.RUNS_DIR)
    runs = list_runs(runs_dir)
    metrics = []
    for r in runs:
        metrics += [k for k in r.get('headline', {}) if k not in metrics]

    rows = []
    for r in runs:
        rid = esc(r['run_id'])
        cells = [f'<td><a href="{rid}/gallery.html" class="mono">{rid}</a>'
                 + (f'<div class="note">{esc(r["label"])}</div>' if r.get('label') else '') + '</td>',
                 f'<td><span class="badge {esc(r.get("status", ""))}">{esc(r.get("status", ""))}</span>'
                 + (f'<div class="note mono">{esc(r["error"]["step"])}</div>' if r.get('error') else '') + '</td>',
                 f'<td class="mono">{esc(r.get("commit_short", ""))}{"*" if r.get("dirty") else ""}</td>',
                 f'<td>{r.get("seconds", 0):.0f}</td>',
                 f'<td>{len(r.get("figures", []))}</td>']
        for k in metrics:
            h = r.get('headline', {}).get(k)
            cells.append(f'<td>{h["irr"]:.3f}</td>' if h else '<td>—</td>')
        cells += [f'<td>{r.get("bytes", 0) / 1e6:.0f}</td>',
                  f'<td><a href="{rid}/gallery.html">gallery</a> · <a href="{rid}/all_figures.pdf">PDF</a> · '
                  f'<a href="{rid}/console.log">log</a> · <a href="{rid}/">folder</a></td>']
        rows.append('<tr>' + ''.join(cells) + '</tr>')

    head = ['Run', 'Status', 'Commit', 'Seconds', 'Figures'] + [f'{esc(k)}' for k in metrics] + ['MB', 'Open']
    latest = f'<a href="{esc(runs[0]["run_id"])}/gallery.html">Open latest run →</a>' if runs else ''
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Cardiac imaging runs</title><style>{CSS}</style></head>
<body>
<header class="top"><div class="wrap"><h1>Cardiac imaging — all runs</h1>
  <div class="meta"><span>{len(runs)} runs in <span class="mono">{esc(runs_dir)}</span></span>{latest}</div></div></header>
<main class="wrap">
  <h2>Run history</h2>
  <p class="note">Headline columns are adjusted density IRRs. <span class="mono">*</span> = run made with uncommitted code changes.</p>
  <details open><summary>Runs, newest first</summary><div class="tablewrap" style="max-height:none">
  <table><thead><tr>{''.join(f'<th>{h}</th>' for h in head)}</tr></thead><tbody>{''.join(rows)}</tbody></table>
  </div></details>
</main>
<footer class="wrap">Generated by cardiac_imaging.reporting.index after every run.</footer>
</body></html>
"""
    (runs_dir / 'index.html').write_text(page, encoding='utf-8')
